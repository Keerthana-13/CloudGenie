"""Discovery statistics: the ticket-data figures quoted in the Stage 1 workbook (rows T1 to T15 and S1).

    python -m evaluation.discovery_stats                  # prints, and writes docs/discovery_stats_output.md

Standard library only. Reads data/development_tickets.json and data/validation_tickets.json.
Every figure in the workbook that comes from the ticket data can be re-derived by running this file.
"""
from __future__ import annotations

import json
import statistics as st
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"


def pct(n: int, d: int) -> str:
    return f"{100 * n / d:.1f}%" if d else "n/a"


def norm(text: str) -> str:
    return " ".join(text.lower().split())


def mean(xs) -> float:
    xs = list(xs)
    return sum(xs) / len(xs) if xs else float("nan")


def build() -> list[str]:
    dev = json.loads((DATA / "development_tickets.json").read_text(encoding="utf-8"))
    val = json.loads((DATA / "validation_tickets.json").read_text(encoding="utf-8"))
    n = len(dev)
    H = lambda t: t["history"]
    L = lambda t: t["labels"]
    out: list[str] = ["# Discovery statistics (development tickets)", "",
                      "Generated by `python -m evaluation.discovery_stats`. These are the figures behind rows T1 to T15 and S1 "
                      "of the Stage 1 workbook.", ""]

    def section(title: str) -> None:
        out.extend(["", f"## {title}", ""])

    # T1
    section("T1 Total tickets")
    dates = sorted(t["received_at"] for t in dev)
    texts = Counter(t["body"] for t in dev)
    repeated = {b: c for b, c in texts.items() if c > 1}
    covered = sum(repeated.values())
    val_in_dev = sum(1 for t in val if t["body"] in texts)
    out += [f"- Tickets: {n}; received {dates[0][:10]} to {dates[-1][:10]}; distinct customers: {len({t['customer_id'] for t in dev})}",
            f"- Distinct ticket texts: {len(texts)} (case-folded and whitespace-normalised: {len({norm(t['body']) for t in dev})})",
            f"- Texts that repeat: {len(repeated)}, covering {covered} tickets ({pct(covered, n)})",
            f"- Validation tickets whose text also appears in development: {val_in_dev} of {len(val)}"]

    # T2
    section("T2 Channel")
    by = defaultdict(list)
    for t in dev:
        by[t["channel"]].append(t)
    for ch, ts in sorted(by.items(), key=lambda kv: -len(kv[1])):
        out.append(f"- {ch}: {len(ts)} ({pct(len(ts), n)}); escalated {pct(sum(H(t)['escalated'] for t in ts), len(ts))}; "
                   f"repeat contact {pct(sum(H(t)['repeat_contact'] for t in ts), len(ts))}; "
                   f"answerable {pct(sum(L(t)['answerable_from_docs'] for t in ts), len(ts))}; "
                   f"median resolution {st.median(H(t)['resolution_time_minutes'] for t in ts):.0f} min; "
                   f"mean satisfaction {mean(H(t)['csat_rating'] for t in ts):.2f}")

    # T3
    section("T3 Intent")
    ic = Counter(L(t)["intent"] for t in dev)
    out.append(f"- {len(ic)} intents; largest {ic.most_common(1)[0][0]} {ic.most_common(1)[0][1]} ({pct(ic.most_common(1)[0][1], n)}); "
               f"smallest {ic.most_common()[-1][0]} {ic.most_common()[-1][1]}")
    out.append("- Counts: " + ", ".join(f"{k} {v}" for k, v in ic.most_common()))

    # T4
    section("T4 Urgency")
    for u in ("medium", "high", "low"):
        ts = [t for t in dev if L(t)["urgency"] == u]
        out.append(f"- {u}: {len(ts)} ({pct(len(ts), n)}); median resolution {st.median(H(t)['resolution_time_minutes'] for t in ts):.0f} min; "
                   f"FCR {pct(sum(H(t)['first_contact_resolution'] for t in ts), len(ts))}")

    # T5, T6
    section("T5 First contact resolution and T6 satisfaction")
    fcr = sum(H(t)["first_contact_resolution"] for t in dev)
    esc = sum(H(t)["escalated"] for t in dev)
    out += [f"- FCR {fcr} of {n} = {pct(fcr, n)}; escalated {esc} = {pct(esc, n)}; FCR equals not-escalated for every ticket: "
            f"{all(H(t)['first_contact_resolution'] == 1 - H(t)['escalated'] for t in dev)}",
            f"- Mean satisfaction {mean(H(t)['csat_rating'] for t in dev):.2f}; ratings present on {sum(1 for t in dev if H(t).get('csat_rating'))} tickets; "
            f"distribution {dict(sorted(Counter(H(t)['csat_rating'] for t in dev).items()))}",
            f"- Resolved at first contact {mean(H(t)['csat_rating'] for t in dev if not H(t)['escalated']):.2f}; "
            f"escalated {mean(H(t)['csat_rating'] for t in dev if H(t)['escalated']):.2f}"]

    # T7
    section("T7 Most frequent questions")
    top = Counter(t["body"] for t in dev).most_common(5)
    for body, c in top:
        out.append(f"- {c} tickets: {body[:110]}")
    out.append(f"- Top five questions: {sum(c for _, c in top)} tickets ({pct(sum(c for _, c in top), n)})")

    # T8
    section("T8 Answerable from documentation")
    ans = sum(L(t)["answerable_from_docs"] for t in dev)
    ans_must = sum(1 for t in dev if L(t)["answerable_from_docs"] and L(t)["must_not_auto_respond"])
    auto = sum(1 for t in dev if L(t)["expected_route"] == "auto_respond")
    out += [f"- Answerable {ans} of {n} = {pct(ans, n)} (not answerable {n - ans})",
            f"- Of the answerable, in never-auto categories: {ans_must}; remaining {ans - ans_must} ({pct(ans - ans_must, n)})",
            f"- Labelled auto_respond: {auto} ({pct(auto, n)})"]

    # T9
    section("T9 Language fluency")
    for f in ("fluent", "non_fluent"):
        ts = [t for t in dev if t["language_fluency"] == f]
        out.append(f"- {f}: {len(ts)} ({pct(len(ts), n)}); FCR {pct(sum(H(t)['first_contact_resolution'] for t in ts), len(ts))}; "
                   f"satisfaction {mean(H(t)['csat_rating'] for t in ts):.2f}; repeat {pct(sum(H(t)['repeat_contact'] for t in ts), len(ts))}; "
                   f"mean resolution {mean(H(t)['resolution_time_minutes'] for t in ts):.0f} min "
                   f"(median {st.median(H(t)['resolution_time_minutes'] for t in ts):.0f}); answerable {pct(sum(L(t)['answerable_from_docs'] for t in ts), len(ts))}")

    # T10, T12
    for code, title, key in (("T10", "Customer tier", "customer_tier"), ("T12", "Region", "customer_region")):
        section(f"{code} {title}")
        g = defaultdict(list)
        for t in dev:
            g[t[key]].append(t)
        for k, ts in sorted(g.items(), key=lambda kv: -len(kv[1])):
            out.append(f"- {k}: {len(ts)} ({pct(len(ts), n)}); FCR {pct(sum(H(t)['first_contact_resolution'] for t in ts), len(ts))}; "
                       f"escalated {pct(sum(H(t)['escalated'] for t in ts), len(ts))}; "
                       f"satisfaction {mean(H(t)['csat_rating'] for t in ts):.2f}; "
                       f"median resolution {st.median(H(t)['resolution_time_minutes'] for t in ts):.0f} min")

    # T11
    section("T11 Repeat contacts")
    rep = sum(H(t)["repeat_contact"] for t in dev)
    out += [f"- Repeat contact {rep} of {n} = {pct(rep, n)}; on escalated tickets {sum(H(t)['repeat_contact'] for t in dev if H(t)['escalated'])}; "
            f"on resolved tickets {sum(H(t)['repeat_contact'] for t in dev if not H(t)['escalated'])}",
            f"- Unanswerable {pct(sum(H(t)['repeat_contact'] for t in dev if not L(t)['answerable_from_docs']), n - ans)}; "
            f"answerable {pct(sum(H(t)['repeat_contact'] for t in dev if L(t)['answerable_from_docs']), ans)}",
            f"- Customers with more than one ticket: {sum(1 for c in Counter(t['customer_id'] for t in dev).values() if c > 1)}; "
            f"most tickets by one customer: {max(Counter(t['customer_id'] for t in dev).values())}"]

    # T13
    section("T13 Arrival times")
    from datetime import datetime
    hours, days = Counter(), Counter()
    for t in dev:
        d = datetime.fromisoformat(t["received_at"].replace("Z", "+00:00"))
        hours[d.hour] += 1
        days[d.strftime("%a")] += 1
    out += [f"- Tickets per hour of day: min {min(hours.values())}, max {max(hours.values())} across {len(hours)} hours",
            "- By weekday: " + ", ".join(f"{k} {v}" for k, v in days.most_common())]

    # T14
    section("T14 Escalated tickets that could have been answered")
    escd = [t for t in dev if H(t)["escalated"]]
    a = [t for t in escd if L(t)["answerable_from_docs"]]
    out += [f"- Escalated {len(escd)}; answerable {len(a)} ({pct(len(a), len(escd))}); "
            f"excluding never-auto categories {sum(1 for t in a if not L(t)['must_not_auto_respond'])} "
            f"({pct(sum(1 for t in a if not L(t)['must_not_auto_respond']), len(escd))}); "
            f"labelled auto_respond {sum(1 for t in escd if L(t)['expected_route'] == 'auto_respond')} "
            f"({pct(sum(1 for t in escd if L(t)['expected_route'] == 'auto_respond'), len(escd))})",
            f"- Answerable-but-escalated as a share of all tickets: {pct(len(a), n)}",
            f"- Mean resolution minutes: escalated {mean(H(t)['resolution_time_minutes'] for t in escd):.1f}, "
            f"resolved {mean(H(t)['resolution_time_minutes'] for t in dev if not H(t)['escalated']):.1f}"]

    # T15
    section("T15 Never auto-answered")
    mn = [t for t in dev if L(t)["must_not_auto_respond"]]
    out += [f"- {len(mn)} of {n} = {pct(len(mn), n)}: " + ", ".join(f"{k} {v}" for k, v in Counter(L(t)['intent'] for t in mn).most_common()),
            f"- All escalated historically: {all(H(t)['escalated'] for t in mn)}; answerable from documentation: "
            f"{sum(1 for t in mn if L(t)['answerable_from_docs'])}"]

    # S1
    section("S1 Ticket data quality")
    routes = defaultdict(set)
    tickets_by_text = Counter(t["body"] for t in dev)
    subjects = defaultdict(set)
    for t in dev:
        routes[t["body"]].add(L(t)["expected_route"])
        subjects[t["body"]].add(t.get("subject", ""))
    both = [b for b, r in routes.items() if len(r) > 1]
    out += [f"- Texts carrying both route labels: {len(both)} (covering {sum(tickets_by_text[b] for b in both)} tickets)",
            f"- Texts whose subject differs between tickets: {sum(1 for s in subjects.values() if len(s) > 1)} of {len(subjects)}",
            f"- Tickets with an empty subject: {sum(1 for t in dev if not t.get('subject'))} "
            f"(all on chat: {all(t['channel'] == 'chat' for t in dev if not t.get('subject'))})",
            f"- Answerable, not sensitive, yet labelled escalate: "
            f"{sum(1 for t in dev if L(t)['answerable_from_docs'] and not L(t)['must_not_auto_respond'] and L(t)['expected_route'] == 'escalate')}"]
    return out


def main() -> int:
    lines = build()
    text = "\n".join(lines) + "\n"
    print(text)
    out = ROOT / "docs" / "discovery_stats_output.md"
    out.write_text(text, encoding="utf-8")
    print(f"written: {out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
